const DIFFICULT_DIR = joinpath(@__DIR__, "..", "difficult_functions")

# Read an exported function, parse it, and compile it into a callable over the
# given argument symbols.
load_difficult(name, argnames::Vector{Symbol}) =
    compile(parse_mathematica(readlines(joinpath(DIFFICULT_DIR, name * ".txt"))[1]), argnames)

